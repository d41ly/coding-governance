#
#   bash <prefix>/roles/return-check.sh < <SubagentStop hook payload>
#
# A THIN SHIM. It resolves a python and runs `handoff.py check-return` beside it with the payload on
# stdin, and that verb does all the work: the role from `agent_type`, the return checked against the
# role's `return` template by `roles_lib.check_return`, the send-back bounded by the policy key
# `roles.retries`, and the record under `<git common dir>/return-check/`. stdout is the verb's, since a
# stop hook's stdout is its decision; every note of this file goes to stderr.
#
# IT FAILS OPEN, ALWAYS. A broken return check never blocks a stop: no python, the wrong shell, and a
# verb that dies each exit 0 with one stderr line. A stop hook's exit 2 blocks the stop, so this file
# never exits 2, and the wrong-shell refusal runs in a subshell whose exit 2 becomes this file's 0.
#
# THE RESOLVER IS INLINE, since this kit is copy-installed as a standalone directory: the blocks below
# are byte-identical to the canonical copies their marker lines name, as `adopt-roles.sh` carries them,
# and the parity population is derived from the marker lines, so this file joins it with no list edit.
#
# Wired by `return-check.fragment.json` beside it: event `SubagentStop`, matcher `*`, interpreter `bash`,
# merged into an install by govkit's fragment wiring and into gov's own settings once by
# `settings-merge.py --fragment`. `check-wiring.sh`'s roles arm grades the wiring.
#
# WHAT THIS DOES NOT CHECK: that the platform continues a subagent whose stop it blocks; the verb's
# record reads one attempt and invalid either way, which is what the driver routes on.
