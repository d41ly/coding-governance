# **Serves:** research PLAY-dClosedLoop-1
"""The whole-design audit's fold inventory, derived: every confirmed and every unverified finding of the three walk
reports, grouped by the clause or item that carries it, so one defect three runs found is one row to fold.

The reports are `reviews/2026-10-20-review-PLAY-dClosedLoop-1-whole-walk-{a,b,c}.md`. A finding's group key is its
address's record and its first anchor: the first clause id (`cl-dClosedLoop-NNNN`) the address names, else its first
item or key tag, else the record and its section tag. Grade and critical class are each group's worst.

Usage (from the worktree root):
  python 2026-10-20-build-PLAY-dClosedLoop-1-fold-inventory.py --out <inventory.md>   write the inventory
  python 2026-10-20-build-PLAY-dClosedLoop-1-fold-inventory.py --check                derive, print counts, write nothing
Exit 2 on a report this script cannot read, or a finding with no address.

What it does not do: judge whether two findings at one address are one defect (a group is a place, and the triage
reads each), or classify a group as a fold, an owner's fork or a later build's work, which the triage records.
"""
import re
import sys
from pathlib import Path

REVIEWS = Path("memory/builds/dClosedLoop/reviews")
RUNS = "abc"
ID = r"[ABC](?:[1-5]|S[1-4])-F\d+"
GRADES = ("blocker", "high", "medium", "low")
SECTIONS = {"Critical": "confirmed", "High": "confirmed", "Medium": "confirmed", "Low": "confirmed",
            "Unverified": "unverified"}


def findings(run):
    path = REVIEWS / f"2026-10-20-review-PLAY-dClosedLoop-1-whole-walk-{run}.md"
    if not path.is_file():
        sys.exit(f"fold-inventory: no report at {path.as_posix()}")
    out, section = [], None
    for block in re.split(r"(?m)^(?=## |### )", path.read_text(encoding="utf-8")):
        h2 = re.match(r"## (\w+)", block)
        if h2:
            section = h2.group(1)
            continue
        m = re.match(r"### (" + ID + r")\b\s*[—-]?\s*(.*)", block)
        if not m or section not in SECTIONS:
            continue
        def field(name):
            f = re.search(r"^- \*\*" + name + r":\*\* (.+)$", block, flags=re.M)
            return f.group(1).strip() if f else ""
        out.append({"run": run.upper(), "id": m.group(1), "title": m.group(2).strip(), "state": SECTIONS[section],
                    "address": field("Address"), "class": field("Class"), "severity": field("Severity").lower(),
                    "same": field("Same as"), "skeptic": field("Skeptic") + " " + field("Second skeptic"),
                    "section": section})
    return out


def key_of(f, by_id):
    addr = f["address"] or by_id.get(re.split(r"[ ,]", f["same"])[0] if f["same"] else "", {}).get("address", "")
    if not addr:
        return None
    rec = re.match(r"`?([a-z0-9-]+)`?", addr)
    clause = re.search(r"cl-dClosedLoop-\d{4}", addr)
    tag = re.search(r"`([a-z]+\.[a-z0-9.<>-]+)`", addr)
    principle = re.search(r"\bP\d{1,2}\b", addr)
    section = re.search(r"\[([a-z0-9-]+)\]", addr)
    anchor = (clause.group(0) if clause else tag.group(1) if tag else principle.group(0) if principle
              else f"[{section.group(1)}]" if section else addr[:40])
    return f"{rec.group(1) if rec else '?'} · {anchor}"


def grade(f, by_id):
    g = f["severity"] or by_id.get(re.split(r"[ ,]", f["same"])[0] if f["same"] else "", {}).get("severity", "")
    s = (re.search(r"(blocker|high|medium|low)", g) if g else None) or re.search(
        r"Confirmed (blocker|high|medium|low)", f["skeptic"], flags=re.I)   # a split's grade is its second skeptic's
    return s.group(1).lower() if s else "unread"


def derive():
    all_ = [f for r in RUNS for f in findings(r)]
    by_id = {f["id"]: f for f in all_}
    groups = {}
    for f in all_:
        k = key_of(f, by_id)
        if k is None:
            sys.exit(f"fold-inventory: {f['id']} has no address and no primary with one")
        f["grade"] = grade(f, by_id)
        f["critical"] = re.search(r"\bc[1-5]\b", f["class"] + " " + by_id.get(f["same"].split(",")[0].strip(), {}).get(
            "class", "")) is not None
        groups.setdefault(k, []).append(f)
    return all_, groups


def worst(fs):
    order = {g: i for i, g in enumerate(GRADES + ("unread",))}
    return min((f["grade"] for f in fs), key=lambda g: order[g])


def render(all_, groups):
    rows = sorted(groups.items(), key=lambda kv: (GRADES.index(worst(kv[1])) if worst(kv[1]) in GRADES else 9,
                                                   not any(f["critical"] for f in kv[1]), kv[0]))
    conf = sum(f["state"] == "confirmed" for f in all_)
    unv = sum(f["state"] == "unverified" for f in all_)
    lines = ["# The whole-design audit's fold inventory", "", "**Serves:** research PLAY-dClosedLoop-1", "",
             "Generated by `build/2026-10-20-build-PLAY-dClosedLoop-1-fold-inventory.py` from the three walk reports; "
             "never edit it by hand. Each row is one place the findings name: the record and the clause or item "
             "that carries them. Rows run worst grade first, critical before the rest.", "",
             f"- **Findings:** {conf} confirmed and {unv} unverified, across runs A, B and C.",
             f"- **Places:** {len(groups)}, {sum(len(v) > 1 for v in groups.values())} of them named by more than one "
             "finding.", "",
             "| # | Place | Worst | Critical | Findings | Titles |", "|---|---|---|---|---|---|"]
    for n, (k, fs) in enumerate(rows, 1):
        ids = ", ".join(f["id"] + ("?" if f["state"] == "unverified" else "") for f in fs)
        titles = " / ".join(dict.fromkeys(f["title"].replace("|", "\\|")[:90] for f in fs))
        lines.append(f"| {n} | {k} | {worst(fs)} | {'yes' if any(f['critical'] for f in fs) else ''} | {ids} | {titles} |")
    lines += ["", "A `?` after an id marks it unverified: a skeptic refuted it and a second confirmed it.", ""]
    return "\n".join(lines)


def main(argv):
    all_, groups = derive()
    text = render(all_, groups)
    print(f"fold-inventory: {sum(f['state'] == 'confirmed' for f in all_)} confirmed, "
          f"{sum(f['state'] == 'unverified' for f in all_)} unverified, {len(groups)} places")
    if "--out" in argv:
        out = Path(argv[argv.index("--out") + 1])
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"fold-inventory: wrote {out.as_posix()}")
    elif "--check" not in argv:
        sys.exit(__doc__.split("\n\n")[2])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
